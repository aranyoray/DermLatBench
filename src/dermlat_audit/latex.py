"""Emit LaTeX macros + tables from metrics.json so the IEEE draft stays in sync.

`dermlat-audit build-paper --output <dir>` writes:
    <dir>/paper/numbers.tex        — \\newcommand macros
    <dir>/paper/tables/*.tex       — booktabs tables
The template at `paper/main.tex` (checked in at repo root) reads both.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from .utils import ensure_dir

# Files shipped with the repo that we copy into the run's output.
_TEMPLATE_FILES = ("main.tex", "refs.bib", "README.md")


def _repo_paper_dir() -> Path:
    return Path(__file__).parent.parent.parent / "paper"


def _fmt_int(n: Any) -> str:
    try:
        return f"{int(n):,}"
    except (TypeError, ValueError):
        return "?"


def _fmt_pct(x: Any, digits: int = 1) -> str:
    try:
        return f"{100.0 * float(x):.{digits}f}\\%"
    except (TypeError, ValueError):
        return "n/a"


def _fmt_float(x: Any, digits: int = 3) -> str:
    try:
        return f"{float(x):.{digits}f}"
    except (TypeError, ValueError):
        return "n/a"


def _macro(name: str, value: str) -> str:
    """Escape a LaTeX macro definition. Value must be TeX-safe already."""
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def write_numbers_tex(metrics: dict[str, Any], out_paper_dir: Path) -> Path:
    """Emit numbers.tex with \\newcommand macros for every headline number."""
    ensure_dir(out_paper_dir)
    d = metrics.get("denominators", {})
    ld = metrics.get("label_distribution", {})
    ans = metrics.get("answerable_split", {})
    ag = metrics.get("supplied_label_agreement", {})
    acc = metrics.get("accuracy_on_answerable_unilateral", {})
    sel = metrics.get("selective", {})
    ab = metrics.get("abstention", {})
    ra = metrics.get("reviewer_agreement", {})
    boot = metrics.get("clustered_bootstrap_accuracy_ci", {})
    calib = metrics.get("calibration", {})
    adv = metrics.get("adversarial_comparison", {})
    inj = metrics.get("injection_scores", {})
    claims = metrics.get("claim_verification", [])

    def _claim_status(name: str) -> str:
        for c in claims:
            if c.get("claim") == name:
                return c.get("status", "NOT_VERIFIABLE").replace("_", "\\_")
        return "NOT\\_VERIFIABLE"

    lines: list[str] = []
    lines.append("% Auto-generated by dermlat-audit build-paper. Do not edit.\n")
    lines.append(_macro("NTotal", _fmt_int(d.get("total_discovered", 0))))
    lines.append(_macro("NProcessed", _fmt_int(d.get("successfully_processed", 0))))
    lines.append(_macro("NCorrupt", _fmt_int(d.get("corrupt", 0))))
    lines.append(_macro("NUnsupported", _fmt_int(d.get("unsupported", 0))))
    lines.append(_macro("NAnswerable", _fmt_int(ans.get("answerable", {}).get("count", 0))))
    lines.append(_macro("NUnanswerable", _fmt_int(ans.get("unanswerable", {}).get("count", 0))))
    lines.append(_macro("NExcluded", _fmt_int(ans.get("excluded", {}).get("count", 0))))
    lines.append(_macro("NLeft", _fmt_int(ld.get("LEFT", {}).get("count", 0))))
    lines.append(_macro("NRight", _fmt_int(ld.get("RIGHT", {}).get("count", 0))))
    lines.append(_macro("NBilateral", _fmt_int(ld.get("BILATERAL_OR_MIDLINE", {}).get("count", 0))))
    lines.append(_macro("SuppliedAgreement", _fmt_pct(ag.get("agreement"))))
    lines.append(_macro("SuppliedAgreementN", _fmt_int(ag.get("n_comparable", 0))))
    lines.append(_macro("AccUnilateral", _fmt_pct(acc.get("accuracy"))))
    lines.append(_macro("AccMacroRecall", _fmt_pct(acc.get("macro_recall"))))
    lines.append(_macro("AccBalanced", _fmt_pct(acc.get("balanced_accuracy"))))
    lines.append(_macro("Coverage", _fmt_pct(sel.get("coverage"))))
    lines.append(_macro("SelAcc", _fmt_pct(sel.get("selective_accuracy"))))
    lines.append(_macro("AbstainSens", _fmt_pct(ab.get("sensitivity"))))
    lines.append(_macro("AbstainSpec", _fmt_pct(ab.get("specificity"))))
    lines.append(_macro("CohensKappa", _fmt_float(ra.get("cohens_kappa", {}).get("kappa"))))
    lines.append(_macro("KrippAlpha", _fmt_float(ra.get("krippendorffs_alpha", {}).get("alpha"))))
    lines.append(_macro("BootPoint", _fmt_pct(boot.get("point"))))
    lines.append(_macro("BootLow", _fmt_pct(boot.get("ci_low"))))
    lines.append(_macro("BootHigh", _fmt_pct(boot.get("ci_high"))))
    lines.append(_macro("BootIter", _fmt_int(boot.get("iterations", 0))))
    lines.append(_macro("ECE", _fmt_float(calib.get("ece"))))
    lines.append(_macro("MCE", _fmt_float(calib.get("mce"))))
    lines.append(_macro("BrierTop", _fmt_float(calib.get("brier_top"))))
    # Adversarial blinding.
    if adv:
        b = adv.get("blinded", {})
        lk = adv.get("leaky", {})
        lines.append(_macro("BlindedAcc", _fmt_pct(b.get("accuracy"))))
        lines.append(_macro("LeakyAcc", _fmt_pct(lk.get("accuracy"))))
        lines.append(_macro("BlindingInflation",
                            _fmt_pct(adv.get("accuracy_inflation_from_leak"))))
        rel = adv.get("relative_inflation_pct")
        lines.append(_macro("BlindingInflationRel",
                            (f"{rel:.1f}\\%" if isinstance(rel, (int, float))
                             else "n/a")))
    else:
        for name in ("BlindedAcc", "LeakyAcc", "BlindingInflation",
                     "BlindingInflationRel"):
            lines.append(_macro(name, "n/a"))
    # Injection validation.
    if inj:
        lf = inj.get("label_flip_detection", {})
        dp = inj.get("duplicate_detection", {})
        lines.append(_macro("InjLabelRecall", _fmt_pct(lf.get("recall"))))
        lines.append(_macro("InjLabelPrec", _fmt_pct(lf.get("precision"))))
        lines.append(_macro("InjLabelKnown", _fmt_int(lf.get("known_flips", 0))))
        lines.append(_macro("InjDupRecall", _fmt_pct(dp.get("recall"))))
        lines.append(_macro("InjDupPrec", _fmt_pct(dp.get("precision"))))
        lines.append(_macro("InjDupKnown", _fmt_int(dp.get("known_duplicates", 0))))
    else:
        for name in ("InjLabelRecall", "InjLabelPrec", "InjLabelKnown",
                     "InjDupRecall", "InjDupPrec", "InjDupKnown"):
            lines.append(_macro(name, "n/a"))
    # Claim verification statuses.
    lines.append(_macro("ClaimTotalStatus", _claim_status("total_images")))
    lines.append(_macro("ClaimAnsStatus", _claim_status("answerable")))
    lines.append(_macro("ClaimUnansStatus", _claim_status("unanswerable")))
    lines.append(_macro("ClaimAgreementStatus", _claim_status("annotation_agreement>threshold")))
    # Readiness.
    ready = metrics.get("publication_ready", False)
    lines.append(_macro("PublicationReady", "true" if ready else "false"))
    lines.append(_macro("ReadyOrNot", "ready" if ready else "not\\ ready"))

    p = out_paper_dir / "numbers.tex"
    p.write_text("".join(lines))
    return p


def _table_claims(claims: list[dict[str, Any]]) -> str:
    lines = [
        "% auto-generated",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Claim verification.}",
        "\\label{tab:claims}",
        "\\begin{tabular}{lrrl}",
        "\\toprule",
        "Claim & Claimed & Observed & Status \\\\",
        "\\midrule",
    ]
    for c in claims:
        claim = str(c.get("claim", "?")).replace("_", "\\_").replace(">", "$>$")
        claimed = c.get("claim_value", "n/a")
        observed = c.get("observed_value", "n/a")
        status = str(c.get("status", "?")).replace("_", "\\_")
        lines.append(f"{claim} & {claimed} & {observed} & {status} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def _table_denominators(d: dict[str, Any]) -> str:
    return "\n".join([
        "% auto-generated",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Denominators — every discovered image accounted for.}",
        "\\label{tab:denom}",
        "\\begin{tabular}{lr}", "\\toprule",
        "Quantity & Count \\\\", "\\midrule",
        f"total\\_discovered & {_fmt_int(d.get('total_discovered', 0))} \\\\",
        f"successfully\\_processed & {_fmt_int(d.get('successfully_processed', 0))} \\\\",
        f"corrupt & {_fmt_int(d.get('corrupt', 0))} \\\\",
        f"unsupported & {_fmt_int(d.get('unsupported', 0))} \\\\",
        f"unprocessed & {_fmt_int(d.get('unprocessed', 0))} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}",
    ]) + "\n"


def _table_injection(inj: dict[str, Any]) -> str:
    if not inj:
        return "% no injection scores available\n"
    lf = inj.get("label_flip_detection", {})
    dp = inj.get("duplicate_detection", {})
    return "\n".join([
        "% auto-generated",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Injection validation — auditor detection of known corruptions.}",
        "\\label{tab:injection}",
        "\\begin{tabular}{lrrrrr}", "\\toprule",
        "Check & Known & TP & FP & Recall & Precision \\\\", "\\midrule",
        f"Label flips & {_fmt_int(lf.get('known_flips', 0))} & {_fmt_int(lf.get('tp', 0))} & "
        f"{_fmt_int(lf.get('fp', 0))} & {_fmt_pct(lf.get('recall'))} & {_fmt_pct(lf.get('precision'))} \\\\",
        f"Duplicates & {_fmt_int(dp.get('known_duplicates', 0))} & {_fmt_int(dp.get('tp', 0))} & "
        f"{_fmt_int(dp.get('fp', 0))} & {_fmt_pct(dp.get('recall'))} & {_fmt_pct(dp.get('precision'))} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}",
    ]) + "\n"


def _table_adversarial(adv: dict[str, Any]) -> str:
    if not adv:
        return "% no adversarial-blinding comparison available\n"
    b = adv.get("blinded", {})
    lk = adv.get("leaky", {})
    return "\n".join([
        "% auto-generated",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Adversarial blinding: accuracy inflation when metadata is leaked.}",
        "\\label{tab:blinding}",
        "\\begin{tabular}{lrrr}", "\\toprule",
        "Setting & N & Correct & Accuracy \\\\", "\\midrule",
        f"Blinded (pixels only) & {_fmt_int(b.get('n', 0))} & {_fmt_int(b.get('correct', 0))} & "
        f"{_fmt_pct(b.get('accuracy'))} \\\\",
        f"Leaked (filename+folder) & {_fmt_int(lk.get('n', 0))} & {_fmt_int(lk.get('correct', 0))} & "
        f"{_fmt_pct(lk.get('accuracy'))} \\\\",
        "\\midrule",
        f"Absolute inflation & \\multicolumn{{2}}{{r}}{{}} & {_fmt_pct(adv.get('accuracy_inflation_from_leak'))} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}",
    ]) + "\n"


def write_tables_tex(metrics: dict[str, Any], out_paper_dir: Path) -> list[Path]:
    tables_dir = ensure_dir(out_paper_dir / "tables")
    outs: list[Path] = []
    d = metrics.get("denominators", {})
    p = tables_dir / "denominators.tex"
    p.write_text(_table_denominators(d))
    outs.append(p)
    p = tables_dir / "claims.tex"
    p.write_text(_table_claims(metrics.get("claim_verification", [])))
    outs.append(p)
    p = tables_dir / "injection.tex"
    p.write_text(_table_injection(metrics.get("injection_scores", {})))
    outs.append(p)
    p = tables_dir / "blinding.tex"
    p.write_text(_table_adversarial(metrics.get("adversarial_comparison", {})))
    outs.append(p)
    return outs


def copy_template(out_paper_dir: Path) -> list[Path]:
    """Copy checked-in main.tex/refs.bib into the run output if not already present."""
    src_dir = _repo_paper_dir()
    if not src_dir.exists():
        return []
    ensure_dir(out_paper_dir)
    copied: list[Path] = []
    for name in _TEMPLATE_FILES:
        src = src_dir / name
        if not src.exists():
            continue
        dst = out_paper_dir / name
        if not dst.exists():
            shutil.copyfile(src, dst)
        copied.append(dst)
    # Also copy figures into paper/figures for convenience.
    fig_src = out_paper_dir.parent / "figures"
    if fig_src.exists():
        fig_dst = ensure_dir(out_paper_dir / "figures")
        for f in fig_src.glob("*.png"):
            shutil.copyfile(f, fig_dst / f.name)
    return copied


def build_paper(metrics: dict[str, Any], out_dir: Path) -> dict[str, Any]:
    """Top-level entry point for `dermlat-audit build-paper`."""
    paper_dir = out_dir / "paper"
    numbers = write_numbers_tex(metrics, paper_dir)
    tables = write_tables_tex(metrics, paper_dir)
    copied = copy_template(paper_dir)
    return {
        "paper_dir": str(paper_dir),
        "numbers_tex": str(numbers),
        "tables": [str(t) for t in tables],
        "template_files": [str(c) for c in copied],
    }


def build_paper_from_metrics_file(metrics_json: Path, out_dir: Path) -> dict[str, Any]:
    metrics = json.loads(metrics_json.read_text())
    return build_paper(metrics, out_dir)
